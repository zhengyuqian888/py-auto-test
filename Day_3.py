# 算数运算符(+-*/加减乘除之外，还有):
#"%"取除法余数，结果应为"1"
print(f"[10%3]的意思是除法取余数，即10/3=3余1，所以结果应为1，验证结果：{10%3}")
#"//"取除法整数，结果应为"3"
print(f"[10//3]的意思是除法取整数，即10/3=3余1，所以结果应为3，验证结果：{10//3}")
#"**"指数（次方），结果应为"1000"
print(f"[10**3]的意思是10的3次方，即10*10*10=1000，所以结果应为1000，验证结果：{10**3}")

#运算符优先级：括号优先级最高，其次先指数，再其他算法，最后加减！！
