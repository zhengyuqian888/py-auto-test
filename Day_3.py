num = 0
# =	赋值运算符	把 = 号右边的结果赋给左边的变量，如 num = 1+2，结果num的值为3
# +=	加法赋值运算符	num += 2 等效于 num = num + 2
num += 2
print(f"num += 2 等效于 num = num + 2,即 num=0+2 所以结果是2，结果验证：{num}")
# -=	减法赋值运算符	num -= 2 等效于 num = num - 2
num -= 2     #注意此时num初始值已为2
print(f"num -= 2 等效于 num = num - 2,即 num=2-2 所以结果是0，结果验证：{num}")
